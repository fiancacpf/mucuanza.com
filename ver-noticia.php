        <h2>Nova ferramenta desenvolvida pelo Tech Lead Constantino Fiança reforça a rastreabilidade e o controlo da correspondência interna.</h2>

        <div class="mt-1">
          <p class="text-justify">A Sociedade Mineira de Mucuanza continua a reforçar as funcionalidades do <b>Sistema Integral de Gestão Mineira (SIGM)</b>, através do desenvolvimento de soluções digitais orientadas para a melhoria dos processos administrativos e da gestão da informação.</p>

          <p class="text-justify">Neste âmbito, <b>Constantino Fiança, Tech Lead, engenheiro de software e responsável pelo desenvolvimento de soluções tecnológicas integradas na Mucuanza</b>, desenvolveu um módulo de gestão e rastreabilidade da correspondência interna, destinado a centralizar o registo, o encaminhamento e o acompanhamento dos documentos no contexto organizacional.</p>

          <p class="text-justify">Integrado no SIGM, o módulo foi concebido para proporcionar maior controlo sobre a circulação da correspondência, permitindo acompanhar os documentos desde o seu registo até à conclusão do respectivo tratamento.</p>

          <p class="text-justify">Com esta integração, o SIGM alarga a sua abrangência funcional à gestão da correspondência, reforçando a centralização da informação e o acompanhamento dos procedimentos internos. A iniciativa enquadra-se no processo de evolução da plataforma, com foco na organização dos fluxos de trabalho, na rastreabilidade documental e no apoio à eficiência administrativa.</p>

          <p class="text-justify">O desenvolvimento desta funcionalidade reflecte a aposta da Sociedade Mineira de Mucuanza na utilização de soluções tecnológicas ajustadas às suas necessidades, contribuindo para a consolidação de ferramentas digitais de suporte à gestão e às actividades da organização.</p>
